/* 一次性、单次 incrementel、逐字节 incremental 三条路径必须给出同一摘要。 */
static int check_sha256(const char *label, const uint8_t *msg, size_t len, const uint8_t *want)
{
    couple_sha256_t ctx;
    uint8_t out[32];
    size_t i;

    couple_sha256(msg, len, out);
    if (memcmp(out, want, 32) != 0) {
        return report_mismatch(label, out, want, 32);
    }

    couple_sha256_init(&ctx);
    couple_sha256_update(&ctx, msg, len);
    couple_sha256_final(&ctx, out);
    if (memcmp(out, want, 32) != 0) {
        return report_mismatch(label, out, want, 32);
    }

    couple_sha256_init(&ctx);
    for (i = 0; i < len; i++) {
        couple_sha256_update(&ctx, msg + i, 1u);
    }
    couple_sha256_final(&ctx, out);
    if (memcmp(out, want, 32) != 0) {
        return report_mismatch(label, out, want, 32);
    }
    return 1;
}

static int check_hmac(const char *label, const uint8_t *key, size_t key_len, const uint8_t *msg,
                      size_t msg_len, const uint8_t *want)
{
    uint8_t out[32];

    couple_hmac_sha256(key, key_len, msg, msg_len, out);
    if (memcmp(out, want, 32) != 0) {
        return report_mismatch(label, out, want, 32);
    }
    return 1;
}

/* 任意分块写入都必须与一次性结果一致（扫 55/56/64/119/120 这些填充边界）。 */
static int check_chunked(const uint8_t *msg, size_t len, const uint8_t *want)
{
    const size_t chunks[] = {1u, 2u, 3u, 7u, 13u, 31u, 55u, 56u, 63u, 64u, 65u, 119u, 120u, 128u};
    couple_sha256_t ctx;
    uint8_t out[32];
    size_t chunk;
    size_t off;
    size_t step;

    for (step = 0; step < (sizeof(chunks) / sizeof(chunks[0])); step++) {
        chunk = chunks[step];
        if (chunk == 0u || chunk > len) {
            continue;
        }
        couple_sha256_init(&ctx);
        for (off = 0; off < len;) {
            size_t take = (len - off < chunk) ? (len - off) : chunk;
            couple_sha256_update(&ctx, msg + off, take);
            off += take;
        }
        couple_sha256_final(&ctx, out);
        if (memcmp(out, want, 32) != 0) {
            fprintf(stderr, "FAIL: chunked (%u) mismatch\n", (unsigned)chunk);
            print_hex("got ", out, 32);
            print_hex("want", want, 32);
            return 0;
        }
    }
    return 1;
}

int main(void)
{
    static uint8_t million_a[1000000];
    static const uint8_t boundary_lens[] = {55u, 56u, 57u, 63u, 64u, 65u, 119u, 120u, 121u, 128u};
    uint8_t boundary[128];
    uint8_t oneshot[32];
    uint8_t key[200];
    uint8_t a[32];
    uint8_t b[32];
    size_t i;

    /* ---- SHA-256 已知答案（一次性 / 单次 incremental / 逐字节 incremental） ---- */
    CHECK(check_sha256("empty", (const uint8_t *)"", 0u, k_sha_empty));
    CHECK(check_sha256("abc", (const uint8_t *)"abc", 3u, k_sha_abc));
    CHECK(check_sha256("448bit(56B)",
                       (const uint8_t *)"abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq",
                       56u, k_sha_448bit));
    CHECK(check_sha256("64byte", (const uint8_t *)k_msg_64, 64u, k_sha_64byte));

    memset(million_a, 'a', sizeof(million_a));
    CHECK(check_sha256("million a", million_a, sizeof(million_a), k_sha_million_a));

    /* ---- 填充边界：55/56/57、63/64/65、119/120/121 字节，任意分块都一致 ---- */
    for (i = 0; i < sizeof(boundary); i++) {
        boundary[i] = (uint8_t)('A' + (i % 26u));
    }
    for (i = 0; i < sizeof(boundary_lens); i++) {
        const size_t n = boundary_lens[i];
        couple_sha256(boundary, n, oneshot);
        if (!check_chunked(boundary, n, oneshot)) {
            fprintf(stderr, "FAIL: boundary length %u\n", (unsigned)n);
            return 1;
        }
    }

    /* ---- HMAC-SHA256：RFC 4231 测试用例 1-7 ---- */
    CHECK(check_hmac("rfc4231 tc1", k_tc1_key, sizeof(k_tc1_key), (const uint8_t *)k_tc1_data,
                     strlen(k_tc1_data), k_tc1_mac));
    CHECK(check_hmac("rfc4231 tc2", (const uint8_t *)k_tc2_key, strlen(k_tc2_key),
                     (const uint8_t *)k_tc2_data, strlen(k_tc2_data), k_tc2_mac));
    CHECK(check_hmac("rfc4231 tc3", k_tc3_key, sizeof(k_tc3_key), k_tc3_data, sizeof(k_tc3_data),
                     k_tc3_mac));
    CHECK(check_hmac("rfc4231 tc4", k_tc4_key, sizeof(k_tc4_key), k_tc4_data, sizeof(k_tc4_data),
                     k_tc4_mac));
    CHECK(check_hmac("rfc4231 tc5", k_tc5_key, sizeof(k_tc5_key), (const uint8_t *)k_tc5_data,
                     strlen(k_tc5_data), k_tc5_mac));
    CHECK(check_hmac("rfc4231 tc6", k_tc67_key, sizeof(k_tc67_key), (const uint8_t *)k_tc6_data,
                     strlen(k_tc6_data), k_tc6_mac));
    CHECK(check_hmac("rfc4231 tc7", k_tc67_key, sizeof(k_tc67_key), (const uint8_t *)k_tc7_data,
                     strlen(k_tc7_data), k_tc7_mac));

    /* 空 key / 空数据也要给出确定结果，不能崩。 */
    memset(key, 0, sizeof(key));
    couple_hmac_sha256(key, 0u, NULL, 0u, oneshot);
    couple_hmac_sha256(NULL, 0u, "", 0u, b);
    CHECK(memcmp(oneshot, b, 32) == 0);

    /* ---- couple_ct_equal ---- */
    for (i = 0; i < sizeof(a); i++) {
        a[i] = (uint8_t)(i * 7u + 3u);
        b[i] = a[i];
    }
    CHECK(couple_ct_equal(a, b, sizeof(a)));
    b[sizeof(b) - 1u] ^= 0x01u;
    CHECK(!couple_ct_equal(a, b, sizeof(a)));
    b[sizeof(b) - 1u] ^= 0x01u;
    b[0] ^= 0x80u;
    CHECK(!couple_ct_equal(a, b, sizeof(a)));
    b[0] ^= 0x80u;

    /* 短缓冲：只比前 1 字节也应能区分。 */
    CHECK(couple_ct_equal(a, b, 1u));
    a[0] ^= 0xffu;
    CHECK(!couple_ct_equal(a, b, 1u));
    CHECK(couple_ct_equal(a, b, 0u)); /* len == 0，没有字节参与比较 */
    a[0] ^= 0xffu;
    CHECK(couple_ct_equal(a, b, sizeof(a)));

    /* 长度不等只能靠指针非法表达：空指针一律 false（fail closed）。 */
    CHECK(!couple_ct_equal(NULL, b, 32u));
    CHECK(!couple_ct_equal(a, NULL, 32u));
    CHECK(!couple_ct_equal(NULL, NULL, 0u));

    puts("couple_sha256 tests: PASS");
    return 0;
}