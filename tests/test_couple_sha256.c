#define CHECK(cond)                                                           \
    do {                                                                      \
        if (!(cond)) {                                                        \
            fprintf(stderr, "FAIL %s:%d: %s\n", __FILE__, __LINE__, #cond);    \
            return 1;                                                         \
        }                                                                     \
    } while (0)

static void print_hex(const char *label, const uint8_t *buf, size_t len)
{
    size_t i;

    fprintf(stderr, "  %s = ", label);
    for (i = 0; i < len; i++) {
        fprintf(stderr, "%02x", (unsigned)buf[i]);
    }
    fputc('\n', stderr);
}

static int report_mismatch(const char *label, const uint8_t *got, const uint8_t *want, size_t len)
{
    fprintf(stderr, "FAIL: digest mismatch for %s\n", label);
    print_hex("got ", got, len);
    print_hex("want", want, len);
    return 0;
}

